import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { Link, MemoryRouter, Route, Routes } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { AppointmentsPage } from './AppointmentsPage.jsx'
import { WaitingRoomGate } from './WaitingRoomGate.jsx'
import { translations } from '../localization/translations.js'
const { repo } = vi.hoisted(() => ({ repo: { mode: 'supabase', listAppointments: vi.fn(), getAppointment: vi.fn(), getDoctor: vi.fn(), listDoctors: vi.fn() } }))
vi.mock('../../services/repositories/index.js', () => ({ presentationRepository: repo }))
vi.mock('../auth/AuthContext.jsx', () => ({ useAuth: () => ({ patient: { id: 'self' } }) }))
vi.mock('../localization/LocalizationContext.jsx', () => ({ useLocalization: () => ({ locale: 'en-MM', t: key => key.split('.').reduce((value, part) => value?.[part], translations.en) || key }) }))
const record = (id, status = 'pending', scheduledAt = '2099-01-01T00:00:00Z') => ({ id, patientId: 'self', doctorId: 'doctor-1', status, scheduledAt, consultationType: 'video', appointmentType: 'teleconsultation', feeMmk: 5000, bookingCode: `REF-${id}`, doctor: { displayName: `Doctor ${id}`, specialty: 'Cardiology' } })
const deferred = () => { let resolve; const promise = new Promise(done => { resolve = done }); return { promise, resolve } }
const view = path => <MemoryRouter initialEntries={[path]}><Link to="/appointments/b">Go B</Link><Routes><Route path="/appointments" element={<AppointmentsPage />} /><Route path="/appointments/:id" element={<AppointmentsPage />} /><Route path="/consultations/:id" element={<WaitingRoomGate />} /></Routes></MemoryRouter>
beforeEach(() => { vi.resetAllMocks(); repo.getDoctor.mockResolvedValue(null); repo.listDoctors.mockResolvedValue([]); repo.listAppointments.mockResolvedValue([]) })
describe('Appointments rendering and route safety', () => {
  it('does not refetch appointment lists when the window regains focus', async () => {
    repo.listAppointments.mockResolvedValueOnce([record('own','pending')]).mockResolvedValueOnce([record('own','confirmed')]).mockResolvedValueOnce([record('own','completed')])
    render(view('/appointments'));await screen.findByText('Pending')
    fireEvent(window,new Event('focus'))
    expect(screen.getByText('Pending')).toBeInTheDocument()
    expect(repo.listAppointments).toHaveBeenCalledTimes(1)
  })
  it('uses the already authorized appointment detail response without a child refetch', async () => {
    repo.getAppointment.mockResolvedValue(record('own'))
    render(view('/appointments/own'))
    expect(await screen.findByText('REF-own')).toBeInTheDocument()
    expect(repo.getAppointment).toHaveBeenCalledTimes(1)
    expect(repo.getAppointment).toHaveBeenCalledWith('own', { patientId: 'self' })
  })
  it('enters the simulated waiting room from the list without requiring a Zoom link', async () => {
    const appointment = record('simulated', 'confirmed', '2099-01-01T00:00:00Z')
    repo.listAppointments.mockResolvedValue([appointment])
    repo.getAppointment.mockResolvedValue(appointment)
    const open = vi.spyOn(window, 'open').mockImplementation(() => null)
    render(view('/appointments'))
    fireEvent.click(await screen.findByRole('link', { name: 'Join Consultation' }))
    expect(await screen.findByText('Device readiness')).toBeInTheDocument()
    expect(screen.getByText('Appointment countdown')).toBeInTheDocument()
    expect(screen.getByText('Recent consultation summaries')).toBeInTheDocument()
    expect(repo.getAppointment).toHaveBeenCalledWith('simulated', { patientId: 'self' })
    expect(open).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Join Waiting Room' }))
    expect(screen.getByText('You are in the demo queue')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Join Consultation' }))
    expect(screen.getByText('Simulated consultation started')).toBeInTheDocument()
    vi.restoreAllMocks()
  })
  it('opens the family presentation appointment in the existing simulated consultation flow without an appointment repository read', async () => {
    render(<MemoryRouter initialEntries={[{ pathname: '/consultations/b60ae0e4-1405-4430-ba33-7603cf87ff0a', state: { easycarePresentationSample: true } }]}><Routes><Route path="/consultations/:id" element={<WaitingRoomGate />} /></Routes></MemoryRouter>)
    expect(await screen.findByRole('heading', { name: 'Consultation Waiting Room' })).toBeInTheDocument()
    expect(screen.getByText('Dr. Su Myat Noe')).toBeInTheDocument()
    expect(screen.getByText('Pediatrics')).toBeInTheDocument()
    expect(repo.getAppointment).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Join Waiting Room' }))
    expect(screen.getByText('You are in the demo queue')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Join Consultation' }))
    expect(screen.getByText('Simulated consultation started')).toBeInTheDocument()
  })
  it('opens Kyaw Aung Moe’s family presentation sample in the same simulated consultation flow', async () => {
    render(<MemoryRouter initialEntries={[{ pathname: '/consultations/e4195430-d6bb-475b-bd3b-354d7439a995', state: { easycarePresentationSample: true } }]}><Routes><Route path="/consultations/:id" element={<WaitingRoomGate />} /></Routes></MemoryRouter>)
    expect(await screen.findByRole('heading', { name: 'Consultation Waiting Room' })).toBeInTheDocument()
    expect(screen.getByText('Dr. Ei Mon Hlaing')).toBeInTheDocument()
    expect(screen.getByText('Dermatology')).toBeInTheDocument()
    expect(repo.getAppointment).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Join Waiting Room' }))
    expect(screen.getByText('You are in the demo queue')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Join Consultation' }))
    expect(screen.getByText('Simulated consultation started')).toBeInTheDocument()
  })
  it('ignores missing or unsafe Zoom links and preserves cancelled/completed eligibility', async () => {
    const appointment = { ...record('missing', 'confirmed'), joinUrl: null }
    repo.listAppointments.mockResolvedValueOnce([appointment])
    repo.getAppointment.mockResolvedValueOnce(appointment)
    const open = vi.spyOn(window, 'open').mockImplementation(() => null)
    const missingView = render(view('/appointments'))
    fireEvent.click(await screen.findByRole('link', { name: 'Join Consultation' }))
    expect(await screen.findByText('Device readiness')).toBeInTheDocument()
    expect(open).not.toHaveBeenCalled()
    missingView.unmount()

    repo.listAppointments.mockResolvedValue([{ ...record('unsafe', 'confirmed'), joinUrl: 'javascript:alert(1)' }])
    render(view('/appointments'))
    expect(await screen.findByRole('link', { name: 'Join Consultation' })).toHaveAttribute('href', '/consultations/unsafe')
    expect(open).not.toHaveBeenCalled()
    cleanup()
    repo.listDoctors.mockResolvedValue([])

    repo.listAppointments.mockResolvedValue([record('cancelled', 'cancelled'), record('completed', 'completed')])
    render(view('/appointments'))
    await screen.findByRole('tab', { name: 'Cancelled' })
    expect(screen.queryByRole('link', { name: 'Join Consultation' })).not.toBeInTheDocument()
    expect(open).not.toHaveBeenCalled()
    open.mockRestore()
  })
  it('uses the same patient-scoped waiting-room route from appointment details', async () => {
    const appointment = { ...record('simulated-detail', 'confirmed') }
    repo.getAppointment.mockResolvedValue(appointment)
    const open = vi.spyOn(window, 'open').mockImplementation(() => null)
    render(view('/appointments/simulated-detail'))
    fireEvent.click(await screen.findByRole('link', { name: 'Join Consultation' }))
    expect(await screen.findByText('Device readiness')).toBeInTheDocument()
    expect(repo.getAppointment).toHaveBeenCalledWith('simulated-detail', { patientId: 'self' })
    expect(open).not.toHaveBeenCalled()
    vi.restoreAllMocks()
  })
  it('denies a waiting-room route when the patient-scoped appointment lookup returns no row', async () => {
    repo.getAppointment.mockResolvedValue(null)
    render(view('/consultations/not-owned'))
    expect(await screen.findByRole('heading', { name: 'Waiting room unavailable' })).toBeInTheDocument()
    expect(screen.getByText(/does not belong to the signed-in patient/i)).toBeInTheDocument()
    expect(repo.getAppointment).toHaveBeenCalledWith('not-owned', { patientId: 'self' })
  })
  it('renders correct Upcoming order, History and keyboard-operable associated tabs', async () => {
    repo.listAppointments.mockResolvedValue([record('later', 'rescheduled', '2099-02-01T00:00:00Z'), record('near'), record('past', 'pending', '2000-01-01T00:00:00Z'), record('done', 'completed'), record('missed', 'no_show'), record('cancel', 'cancelled')])
    render(view('/appointments')); const upcoming = await screen.findByRole('tab', { name: 'Upcoming' })
    expect(screen.queryByText('Follow-up Instructions from Documents')).not.toBeInTheDocument()
    const appointmentsHeader = screen.getByRole('heading', { name: 'Appointments' }).closest('header')
    expect(appointmentsHeader.nextElementSibling).toHaveAttribute('role', 'tablist')
    expect(appointmentsHeader.nextElementSibling.nextElementSibling).toHaveAttribute('id', 'appointment-panel')
    fireEvent.click(upcoming)
    const panel = screen.getByRole('tabpanel', { name: 'Upcoming' })
    expect(within(panel).getAllByRole('heading').filter(node => node.textContent.startsWith('Doctor')).map(node => node.textContent)).toEqual(['Doctor near', 'Doctor later'])
    expect(within(panel).getByText('Rescheduled')).toBeInTheDocument()
    expect(screen.queryByText('Doctor past')).not.toBeInTheDocument()
    fireEvent.keyDown(upcoming, { key: 'ArrowRight' })
    expect(screen.getByRole('tab', { name: 'History' })).toHaveFocus()
    expect(screen.getByText('Doctor missed')).toBeInTheDocument()
    expect(screen.getByText('No show')).toBeInTheDocument()
    expect(screen.getByText('Doctor done')).toBeInTheDocument()
    expect(screen.queryByText('Doctor cancel')).not.toBeInTheDocument()
    expect(repo.listAppointments).toHaveBeenCalledWith({ patientId: 'self' })
    expect(screen.queryByRole('button', { name: 'Cancel Appointment' })).not.toBeInTheDocument()
  })
  it('discards a late A request after routing to missing B', async () => {
    const a = deferred(); const b = deferred()
    repo.getAppointment.mockImplementation(id => id === 'a' ? a.promise : b.promise)
    render(view('/appointments/a')); fireEvent.click(screen.getByText('Go B'))
    expect(screen.getByRole('status')).toHaveTextContent('Loading appointments')
    await act(async () => { b.resolve(null) })
    expect(screen.getByRole('heading', { name: 'Appointment not found' })).toBeInTheDocument()
    await act(async () => { a.resolve(record('a')) })
    expect(screen.queryByText('Doctor a')).not.toBeInTheDocument()
  })
  it('clears loaded A immediately on B navigation and does not restore A after denied refresh', async () => {
    const secondA = deferred(); const b = deferred(); let calls = 0
    repo.getAppointment.mockImplementation(id => id === 'b' ? b.promise : ++calls === 1 ? Promise.resolve(record('a')) : secondA.promise)
    render(view('/appointments/a')); expect(await screen.findByText('Doctor a')).toBeInTheDocument()
    fireEvent.click(screen.getByText('Go B'))
    expect(screen.queryByText('Doctor a')).not.toBeInTheDocument()
    await act(async () => { secondA.resolve(null); b.resolve(null) })
    expect(screen.getByRole('heading', { name: 'Appointment not found' })).toBeInTheDocument()
    expect(screen.queryByText('REF-a')).not.toBeInTheDocument()
  })
})
