import { act, fireEvent, render, screen } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { ProviderAppointmentsPage } from './ProviderAppointmentsPage.jsx'
const state = vi.hoisted(() => ({ auth: { provider: { id: 'one' } }, list: vi.fn(), transition: vi.fn() }))
vi.mock('../auth/AuthContext.jsx', () => ({ useAuth: () => state.auth }))
vi.mock('../../services/providerAppointmentService.js', () => ({ providerAppointmentService: { list: state.list, transition: state.transition } }))
const row = status => ({ id: 'own', patient_display_name: 'Authorized Patient', scheduled_start: '2099-01-01T09:00:00Z', scheduled_end: '2099-01-01T09:30:00Z', consultation_channel: 'video', reason_symptoms: 'Test reason', fee_amount: '25000.00', currency: 'MMK', booking_code: 'REF-ONE', status })
beforeEach(() => { vi.resetAllMocks(); state.auth={provider:{id:'one'}};state.list.mockResolvedValue([row('pending')]) })
describe('provider appointment workspace', () => {
  it('opens pending appointment, confirms and completes using canonical re-reads', async () => {
    state.list.mockResolvedValueOnce([row('pending')]).mockResolvedValueOnce([row('confirmed')]).mockResolvedValueOnce([row('completed')])
    state.transition.mockResolvedValue('confirmed')
    render(<ProviderAppointmentsPage />)
    fireEvent.click(await screen.findByRole('button', {name:'Open appointment'}))
    expect(screen.getByText('Fee: 25,000 MMK')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', {name:'Confirm'}))
    await screen.findByText('Video consultation · Confirmed')
    fireEvent.click(screen.getByRole('button', {name:'Open appointment'}))
    fireEvent.click(screen.getByRole('button', {name:'Mark Completed'}))
    await screen.findByText('Video consultation · Completed')
    expect(state.transition.mock.calls).toEqual([['own','confirmed'],['own','completed']])
    fireEvent.click(screen.getByRole('button', {name:'Open appointment'}))
    expect(screen.queryByRole('button', {name:'Confirm'})).not.toBeInTheDocument()
    expect(screen.queryByRole('button', {name:'Mark Completed'})).not.toBeInTheDocument()
  })
  it('offers no-show only for confirmed appointments and rereads the canonical result', async () => {
    state.list.mockResolvedValueOnce([row('confirmed')]).mockResolvedValueOnce([row('no_show')]);state.transition.mockResolvedValue('no_show')
    render(<ProviderAppointmentsPage />);fireEvent.click(await screen.findByRole('button',{name:'Open appointment'}))
    fireEvent.click(screen.getByRole('button',{name:'Mark No-show'}))
    expect(state.transition).toHaveBeenCalledWith('own','no_show')
    expect(await screen.findByText('Video consultation · No-show')).toBeInTheDocument()
    expect(state.list).toHaveBeenCalledTimes(2)
  })
  it('clears data on uncertain mutation failure and requires retry read', async () => {
    state.transition.mockRejectedValue(new Error('Reload current status'))
    render(<ProviderAppointmentsPage />);fireEvent.click(await screen.findByRole('button',{name:'Open appointment'}))
    fireEvent.click(screen.getByRole('button',{name:'Confirm'}))
    await screen.findByRole('alert');expect(screen.queryByText('Authorized Patient')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button',{name:'Try again'}));await screen.findByText('Authorized Patient')
    expect(state.list).toHaveBeenCalledTimes(2)
  })
  it('discards previous provider responses after account switch', async () => {
    let resolve;state.list.mockReturnValueOnce(new Promise(done=>{resolve=done})).mockResolvedValueOnce([])
    const view=render(<ProviderAppointmentsPage />)
    state.auth={provider:{id:'two'}};view.rerender(<ProviderAppointmentsPage />)
    await screen.findByText('No appointments assigned to you.')
    await act(async()=>resolve([row('pending')]))
    expect(screen.queryByText('Authorized Patient')).not.toBeInTheDocument()
  })
})
