import { StrictMode } from 'react'
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { CervicalWellnessReminders } from './CervicalWellnessReminders.jsx'
import { CERVICAL_REMINDERS } from './cervicalReminderSequence.js'
import { LocalizationProvider } from '../localization/LocalizationContext.jsx'
const { auth, persist } = vi.hoisted(() => ({ auth: {}, persist: vi.fn() }))
vi.mock('../auth/AuthContext.jsx', () => ({ useAuth: () => auth }))
vi.mock('../../services/notificationService.js', () => ({ notificationService: { persistDailyCervicalWellness: persist } }))
let sessionNumber = 0
beforeEach(() => {
  vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout', 'Date'] })
  sessionStorage.clear(); persist.mockReset().mockResolvedValue(10)
  Object.assign(auth, { status: 'authenticated', workspace: 'patient', role: 'patient', user: { id: 'owner' },
    patient: { id: '2d329d5b-9093-45ca-a980-97466d2a71eb', auth_user_id: 'owner' },
    session: { access_token: `header.${btoa(JSON.stringify({ session_id: `00000000-0000-4000-8000-${String(++sessionNumber).padStart(12, '0')}` }))}.signature` } })
})
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.useRealTimers() })
const tick = ms => act(() => vi.advanceTimersByTime(ms))
const close = () => fireEvent.click(screen.getByRole('button', { name: 'Dismiss wellness reminder' }))
const replay = () => fireEvent.click(screen.getByRole('button', { name: 'Replay Wellness Reminders' }))
it('requires two dismissals before exactly 8000ms, shows one cervical reminder, and stops on third X', () => {
  const view = render(<StrictMode><CervicalWellnessReminders /></StrictMode>)
  expect(screen.getByText('How are you feeling today?')).toBeInTheDocument()
  tick(80000)
  expect(screen.getByText('How are you feeling today?')).toBeInTheDocument()
  close()
  expect(screen.getByText("Don't forget to take your medicine today")).toBeInTheDocument()
  tick(80000)
  expect(screen.getByText("Don't forget to take your medicine today")).toBeInTheDocument()
  close(); expect(screen.queryByRole('status')).not.toBeInTheDocument()
  tick(7999); expect(screen.queryByRole('status')).not.toBeInTheDocument()
  view.rerender(<StrictMode><CervicalWellnessReminders /></StrictMode>)
  tick(1); expect(screen.getByText(CERVICAL_REMINDERS[0].en)).toBeInTheDocument()
  expect(screen.getAllByRole('status')).toHaveLength(1)
  tick(9999); expect(screen.getByText(CERVICAL_REMINDERS[0].en)).toBeInTheDocument()
  tick(1); expect(screen.getByText(CERVICAL_REMINDERS[1].en)).toBeInTheDocument()
  close(); tick(80000)
  view.rerender(<StrictMode><CervicalWellnessReminders /></StrictMode>)
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
  view.unmount(); render(<CervicalWellnessReminders />)
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
})
it('resumes the saved waiting deadline on route remount and token refresh', () => {
  const view = render(<CervicalWellnessReminders />)
  close(); close(); tick(3000); view.unmount()
  expect(vi.getTimerCount()).toBe(0)
  auth.session.access_token += '-refreshed'
  render(<CervicalWellnessReminders />)
  tick(4999); expect(screen.queryByRole('status')).not.toBeInTheDocument()
  tick(1); expect(screen.getByText(CERVICAL_REMINDERS[0].en)).toBeInTheDocument()
})
it('replay starts cervical directly, cancels waiting, and restarts from first after X without DB writes', () => {
  const schedule = vi.spyOn(globalThis, 'setTimeout')
  const cancel = vi.spyOn(globalThis, 'clearTimeout')
  const view = render(<CervicalWellnessReminders />)
  close(); close(); tick(4000)
  const index = schedule.mock.calls.findLastIndex(([, delay]) => delay === 8000)
  replay()
  expect(cancel).toHaveBeenCalledWith(schedule.mock.results[index].value)
  expect(screen.getByText(CERVICAL_REMINDERS[0].en)).toBeInTheDocument()
  expect(screen.queryByText('How are you feeling today?')).not.toBeInTheDocument()
  expect(screen.queryByText("Don't forget to take your medicine today")).not.toBeInTheDocument()
  tick(9999); expect(screen.getByText(CERVICAL_REMINDERS[0].en)).toBeInTheDocument()
  tick(1); expect(screen.getByText(CERVICAL_REMINDERS[1].en)).toBeInTheDocument()
  close(); tick(80000)
  view.rerender(<CervicalWellnessReminders />)
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
  view.unmount(); render(<CervicalWellnessReminders />)
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
  const calls = persist.mock.calls.length
  replay(); expect(screen.getByText(CERVICAL_REMINDERS[0].en)).toBeInTheDocument()
  replay(); tick(10000)
  expect(screen.getByText(CERVICAL_REMINDERS[1].en)).toBeInTheDocument()
  expect(screen.getAllByRole('status')).toHaveLength(1)
  expect(persist).toHaveBeenCalledTimes(calls)
})
it('plays all ten reminders in order and completes without stacking', () => {
  render(<CervicalWellnessReminders />); replay()
  for (const message of CERVICAL_REMINDERS) {
    expect(screen.getByText(message.en)).toBeInTheDocument()
    expect(screen.getByText(message.my)).toHaveAttribute('lang', 'my')
    expect(screen.getByText(message.en)).toHaveAttribute('lang', 'en')
    expect(screen.getByRole('status').children[0]).toHaveTextContent(message.my)
    expect(screen.getByRole('status').children[1]).toHaveTextContent(message.en)
    expect(screen.getAllByRole('status')).toHaveLength(1)
    tick(10000)
  }
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
  tick(80000); expect(screen.queryByRole('status')).not.toBeInTheDocument()
})
it('keeps both translations when Myanmar is selected and cancels the cervical timer on unmount', () => {
  sessionStorage.setItem('easycare-language', 'my')
  const schedule = vi.spyOn(globalThis, 'setTimeout')
  const cancel = vi.spyOn(globalThis, 'clearTimeout')
  const view = render(<LocalizationProvider><CervicalWellnessReminders /></LocalizationProvider>)
  replay()
  expect(screen.getByText(CERVICAL_REMINDERS[0].my)).toHaveAttribute('lang', 'my')
  expect(screen.getByText(CERVICAL_REMINDERS[0].en)).toHaveAttribute('lang', 'en')
  tick(10000)
  expect(screen.getByText(CERVICAL_REMINDERS[1].my)).toBeInTheDocument()
  const index = schedule.mock.calls.findLastIndex(([, delay]) => delay === 10000)
  view.unmount()
  expect(cancel).toHaveBeenCalledWith(schedule.mock.results[index].value)
})
it('clears waiting timer on logout and excludes other patients', () => {
  const schedule = vi.spyOn(globalThis, 'setTimeout')
  const cancel = vi.spyOn(globalThis, 'clearTimeout')
  const view = render(<CervicalWellnessReminders />)
  close(); close(); auth.status = 'anonymous'; view.rerender(<CervicalWellnessReminders />)
  const index = schedule.mock.calls.findLastIndex(([, delay]) => delay === 8000)
  expect(cancel).toHaveBeenCalledWith(schedule.mock.results[index].value)
  tick(80000)
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
  auth.status = 'authenticated'; auth.patient.id = 'other'; view.rerender(<CervicalWellnessReminders />)
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
})


